"""
rice.py: «рисовый массив» и правила зон внутри него (issue #19).

Рисовый массив это пиксели, которые весной были ЗАТОПЛЕНЫ (рис растёт в чеках с водой).
Летняя зелень условием не является: трава на сухой земле не затоплялась и рисом не станет.
Внутри массива зоны определяются по состоянию летом (healthy, stress, salinity, water, empty),
вне массива пиксель «не рисовое поле».

Признак затопления: стандарт для рисовых чеков (Xiao et al., 2005, «Mapping paddy rice
agriculture in southern China using multi-temporal MODIS images», Remote Sensing of Environment, 95).
Пиксель затоплен на дату, если  LSWI + 0.05 >= NDVI,  где LSWI = (B8 - B11) / (B8 + B11).
Берём, был ли пиксель затоплен хотя бы на одном безоблачном весеннем снимке.
Формула дана в задании; название статьи и журнал записаны по памяти, саму статью мы не проверяли.

Все пороги лежат здесь, в одном месте. Меняйте только их.
"""
import numpy as np

# ---------- Затопление ----------
# Когда заливают рис. В Кызылорде чеки заливают с конца апреля до середины июня,
# в разные дни, поэтому смотрим все безоблачные снимки за это время.
SPRING_FROM = "2025-04-20"
SPRING_TO = "2025-06-20"

# Облачность. Снимок берём, если НАД ПОЛЕМ (в контуре или квадрате) облаков и теней по SCL
# меньше MAX_FIELD_CLOUD пикселей. Облачность всей сцены, которую считает Copernicus,
# про поле почти ничего не говорит, поэтому она только грубый предфильтр.
MAX_FIELD_CLOUD = 0.20      # доля пикселей поля в облаках и тенях, не меньше: снимок пропускаем
SCENE_CLOUD_PREFILTER = 80  # облачность сцены, %: выше этого снимок не запрашиваем вовсе

# Xiao et al., 2005: пиксель затоплен, если LSWI + LSWI_MARGIN >= NDVI.
# Эту же формулу повторяет evalscript в spring.py (он считается на сервере).
LSWI_MARGIN = 0.05

# ---------- Зоны внутри рисового массива (по NDVI, SI и NDWI выбранного месяца) ----------
HEALTHY_NDVI = 0.6   # NDVI выше: здоровый рис (README: рис в росте 0.6-0.9)
STRESS_NDVI = 0.3    # от 0.3 до 0.6: стресс; ниже 0.3: растений почти нет (соль, вода, пусто)

# «Высокий SI». SI = sqrt(B2 * B4). На наших полях (июль и август) у пикселей с NDVI < 0.3:
# сухая светлая земля и соль дают SI 0.11-0.24, вода и тень 0.03-0.05, зелёный рис 0.02-0.03.
# Порог 0.10 лежит между ними. Это первое приближение: проверить по ручной разметке (issue #10).
SALT_SI = 0.10
WATER_NDWI = 0.0     # NDWI выше 0: вода в месяце снимка (README, раздел 3.2)

# Меньше такой доли рисового массива в квадрате: «здесь не рисовое поле».
MIN_RICE_SHARE = 0.30


def is_flooded(ndvi, lswi):
    """
    Затоплен ли пиксель на одну дату: LSWI + 0.05 >= NDVI (Xiao et al., 2005).
    Работает с числами и массивами. NaN (нет данных) даёт False.
    """
    return (np.asarray(lswi) + LSWI_MARGIN) >= np.asarray(ndvi)


def summer_ndvi(*ndvi_arrays):
    """
    Лучший NDVI за лето: для каждого пикселя большее из июля и августа.
    NaN в одном месяце не мешает, если в другом данные есть.
    """
    best = np.asarray(ndvi_arrays[0], dtype="float32")
    for other in ndvi_arrays[1:]:
        best = np.fmax(best, other)   # fmax: если одно число NaN, берётся другое
    return best


def rice_array(flooded, field_mask, summer=None):
    """
    Рисовый массив: True = пиксель затоплен весной.

      flooded    - True там, где пиксель был затоплен хотя бы на одном весеннем снимке,
                   или None, если безоблачных весенних снимков нет
      field_mask - True внутри поля
      summer     - NDVI лета (summer_ndvi), нужен только для запасного варианта

    Запасной вариант (flooded=None): весны нет, поэтому считаем рисом пиксели с
    NDVI лета выше HEALTHY_NDVI. Тогда в ответе должна быть пометка «без проверки затопления».
    """
    if flooded is None:
        return (summer > HEALTHY_NDVI) & field_mask   # NaN > число = False
    return flooded & field_mask


def rice_share(rice, field_mask):
    """Доля рисового массива среди пикселей поля: число от 0 до 1."""
    total = int(field_mask.sum())
    if total == 0:
        return 0.0
    return float(rice.sum()) / total


def is_rice_field(share):
    """True, если рисового массива достаточно (не меньше MIN_RICE_SHARE)."""
    return share >= MIN_RICE_SHARE
