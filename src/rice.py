"""
rice.py: маска «рисовое поле» (issue #19).

Одного летнего NDVI мало: степные кустарники и трава тоже зелёные, и программа
принимала их за рис. Поэтому рисом считаем пиксель, который
  1. весной был ЗАТОПЛЕН (рис растёт в чеках с водой), И
  2. в июле или августе имеет ВЫСОКИЙ NDVI (рис вырос).
Трава на сухой земле второго условия не выполняет и рисом не становится.

Все пороги лежат здесь, в одном месте. Меняйте только их.
"""
import numpy as np

# ---------- Пороги ----------
# Когда заливают рис. В Кызылорде чеки заливают с конца апреля до середины июня,
# в разные дни, поэтому один майский снимок воду может не поймать (так было на поле 2).
# Смотрим все безоблачные снимки за это время и берём максимум NDWI.
SPRING_FROM = "2025-04-20"
SPRING_TO = "2025-06-20"

# «Был затоплен»: максимум NDWI за весну больше этого числа.
# NDWI > 0 это открытая вода (McFeeters, 1996). Порог не занижаем: при NDWI около -0.15
# это уже сухая голая земля, и проверка воды перестала бы что-то проверять.
FLOOD_NDWI = 0.0

# «Рис вырос»: лучший из NDVI июля и августа больше этого числа.
# README, раздел 3.2: рис в росте имеет NDVI 0.6-0.9. Проверка на наших данных:
# степь у солончака (45.0123, 64.6012): 95% пикселей ниже 0.53, выше 0.6 только 2%;
# поля 1-3: выше 0.6 от 51% до 97% пикселей.
RICE_NDVI = 0.6

# Рисовых пикселей меньше этой доли квадрата: «здесь не рисовое поле».
MIN_RICE_SHARE = 0.30


def summer_ndvi(*ndvi_arrays):
    """
    Лучший NDVI за лето: для каждого пикселя большее из июля и августа.
    NaN (нет данных) в одном месяце не мешает, если в другом данные есть.
    """
    best = np.asarray(ndvi_arrays[0], dtype="float32")
    for other in ndvi_arrays[1:]:
        best = np.fmax(best, other)   # fmax: если одно число NaN, берётся другое
    return best


def rice_mask(summer, flood, field_mask):
    """
    Маска рисовых пикселей: True = рис.

      summer     - NDVI лета (summer_ndvi)
      flood      - максимум NDWI за весну, или None, если весенних снимков нет
      field_mask - True внутри поля

    Если весенних снимков нет (flood=None), запасной вариант: только летний NDVI.
    Тогда ответ нужно пометить «без проверки затопления».
    """
    green = summer > RICE_NDVI            # NaN > число = False, поэтому NaN рисом не станет
    if flood is None:
        return green & field_mask
    return green & (flood > FLOOD_NDWI) & field_mask


def rice_share(rice, field_mask):
    """Доля рисовых пикселей среди пикселей поля: число от 0 до 1."""
    total = int(field_mask.sum())
    if total == 0:
        return 0.0
    return float(rice.sum()) / total


def is_rice_field(share):
    """True, если риса достаточно (не меньше MIN_RICE_SHARE)."""
    return share >= MIN_RICE_SHARE
